#!/usr/bin/env bash
# setup-wsl-mesh.sh — provision lnsd + serial LoRa + MeshChatX on WSL2.
#
# Covers everything docs/src/guide/wsl.md explains:
#   * apt deps (python3.12, venv)
#   * optional .deb install of leviculum (lnsd)
#   * udev rules for stable /dev/leviculum-* device names
#   * /etc/reticulum/config: TCP server :4242 + one SerialInterface per
#     attached board (auto-detected by udev symlinks) + optional public
#     TCP uplinks
#   * leviculum group + storage permissions
#   * systemd service for lnsd, systemd --user service for MeshChatX
#
# USB passthrough itself (usbipd) must be done on the Windows side —
# see the doc. Re-run any time; every step is idempotent.
#
# Usage:
#   scripts/setup-wsl-mesh.sh [--deb PATH] [--no-meshchatx] [--no-internet]
#                             [--freq HZ] [--sf N] [--bw HZ] [--cr N] [--txp DBM]
#                             [--serial SERIAL]

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SUDO="sudo"
CFG=/etc/reticulum/config

DEB=""
DO_MESHCHATX=1
DO_INTERNET=1
# EU868 defaults matching the known-good config.
FREQ=869463000; BW=125000; SF=8; CR=5; TXP=22
FORCED_SERIAL=""

while [ $# -gt 0 ]; do
    case "$1" in
        --deb)          DEB="$2"; shift 2 ;;
        --no-meshchatx) DO_MESHCHATX=0; shift ;;
        --no-internet)  DO_INTERNET=0; shift ;;
        --freq)         FREQ="$2"; shift 2 ;;
        --bw)           BW="$2"; shift 2 ;;
        --sf)           SF="$2"; shift 2 ;;
        --cr)           CR="$2"; shift 2 ;;
        --txp)          TXP="$2"; shift 2 ;;
        --serial)       FORCED_SERIAL="$2"; shift 2 ;;
        -h|--help)      sed -n '2,25p' "$0"; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

say()  { printf '\033[1m== %s\033[0m\n' "$*"; }
warn() { printf '\033[33m!! %s\033[0m\n' "$*" >&2; }

grep -qi microsoft /proc/version 2>/dev/null \
    || warn "/proc/version does not look like WSL — continuing anyway."

command -v sudo >/dev/null || { echo "sudo not found"; exit 1; }
sudo -v

# ── 1. packages ────────────────────────────────────────────────────
say "1/8  apt dependencies"
PKGS=()
command -v python3.12 >/dev/null || PKGS+=(python3.12)
python3.12 -m venv --help >/dev/null 2>&1 || PKGS+=(python3.12-venv)
if [ ${#PKGS[@]} -gt 0 ]; then
    sudo apt-get update -qq
    sudo apt-get install -y "${PKGS[@]}"
else
    echo "   python3.12 + venv already present"
fi

# ── 2. leviculum package ───────────────────────────────────────────
say "2/8  lnsd package"
if [ -n "$DEB" ]; then
    sudo dpkg -i "$DEB" || sudo apt-get -f install -y
elif command -v lnsd >/dev/null; then
    echo "   lnsd already installed: $(command -v lnsd)"
else
    warn "   lnsd not installed and no --deb given — skipping (install the .deb and re-run)"
fi

# ── 3. udev rules ──────────────────────────────────────────────────
say "3/8  udev rules for stable /dev/leviculum-* names"
RULES_SRC="$REPO_ROOT/leviculum-nrf/udev/99-leviculum.rules"
if [ -f "$RULES_SRC" ]; then
    if ! cmp -s "$RULES_SRC" /etc/udev/rules.d/99-leviculum.rules 2>/dev/null; then
        sudo cp "$RULES_SRC" /etc/udev/rules.d/
        sudo udevadm control --reload-rules
        sudo udevadm trigger || true
        echo "   installed 99-leviculum.rules"
    else
        echo "   already current"
    fi
else
    warn "   $RULES_SRC missing — skipping"
fi

# ── 4. detect boards ───────────────────────────────────────────────
say "4/8  detecting LoRa boards"
declare -a PORTS=()
if [ -n "$FORCED_SERIAL" ]; then
    for p in /dev/leviculum-*-transport-"$FORCED_SERIAL" /dev/leviculum-*-transport; do
        [ -e "$p" ] && PORTS+=("$p")
    done
    [ ${#PORTS[@]} -eq 0 ] && warn "   no board matching serial $FORCED_SERIAL"
else
    # Prefer the serial-numbered symlinks; never the unsuffixed ones.
    for p in /dev/leviculum-*-transport-*; do
        [ -e "$p" ] && PORTS+=("$p")
    done
fi
if [ ${#PORTS[@]} -eq 0 ]; then
    warn "   no leviculum transport ports found — is a board attached via usbipd?"
fi
printf '   %s\n' "${PORTS[@]:-none}"

# ── 5. /etc/reticulum/config ───────────────────────────────────────
say "5/8  writing $CFG"
{
cat <<EOF
# Generated by scripts/setup-wsl-mesh.sh — edits survive via the
# [interfaces] section below; regenerate with the same flags.

[reticulum]
  # True so peers dialing in over TCP (e.g. Windows-side MeshChatX)
  # get their announces relayed onward. Leaf-only use can say False.
  enable_transport = True
  share_instance = Yes
  instance_name = default

[logging]
  loglevel = 4

[interfaces]

  # Clients dialing in: Windows MeshChatX via WSL localhost-forward.
  [[TCP]]
    type = TCPServerInterface
    enabled = yes
    listen_ip = 0.0.0.0
    listen_port = 4242
EOF

n=0
for port in "${PORTS[@]:-}"; do
    [ -e "$port" ] || continue
    n=$((n+1))
    name="$(basename "$port" | sed 's/^leviculum-//')"
    cat <<EOF

  [[LNode $name]]
    type = SerialInterface
    enabled = yes
    port = $port
    speed = 115200
    databits = 8
    parity = none
    stopbits = 1
    # LoRa PHY pushed to the board (adjust to your band plan).
    frequency = $FREQ
    bandwidth = $BW
    spreadingfactor = $SF
    codingrate = $CR
    txpower = $TXP
EOF
done

if [ "$DO_INTERNET" -eq 1 ]; then
cat <<EOF

  # Public community TCP uplinks (official testnet hosts are dead DNS).
  [[RNS TCP Node Germany 001]]
    type = TCPClientInterface
    enabled = yes
    target_host = 202.61.243.41
    target_port = 4965

  [[RNS TCP Node Germany 002]]
    type = TCPClientInterface
    enabled = yes
    target_host = 193.26.158.230
    target_port = 4965

  [[RNS Transport US-East]]
    type = TCPClientInterface
    enabled = yes
    target_host = 45.77.109.86
    target_port = 4965
EOF
fi
} | sudo tee "$CFG" >/dev/null
echo "   wrote $CFG with $n serial interface(s), internet=$DO_INTERNET"

# ── 6. groups + storage permissions ────────────────────────────────
say "6/8  groups and storage permissions"
sudo usermod -aG leviculum,dialout "$USER" || true
# Directories created by non-leviculum tools must stay group-writable,
# else the daemon's ratchet/storage writes fail EACCES.
[ -d /etc/reticulum/storage ] && sudo chmod -R g+w /etc/reticulum/storage
echo "   $USER in leviculum+dialout; storage g+w"

# ── 7. lnsd service ────────────────────────────────────────────────
say "7/8  lnsd service"
if systemctl cat lnsd.service >/dev/null 2>&1; then
    sudo systemctl enable lnsd.service >/dev/null 2>&1 || true
    sudo systemctl restart lnsd.service
    sleep 2
    systemctl is-active --quiet lnsd.service && echo "   lnsd active" \
        || { warn "   lnsd failed to start — journalctl -u lnsd"; }
else
    warn "   no lnsd.service unit — daemon not installed?"
fi

# ── 8. MeshChatX ───────────────────────────────────────────────────
if [ "$DO_MESHCHATX" -eq 1 ]; then
    say "8/8  MeshChatX (venv + systemd --user)"
    python3.12 -m venv ~/.venvs/meshchatx
    ~/.venvs/meshchatx/bin/pip install --quiet --upgrade pip
    ~/.venvs/meshchatx/bin/pip install --quiet reticulum-meshchatx

    mkdir -p ~/.config/systemd/user ~/.meshchatx
    cat > ~/.config/systemd/user/meshchatx.service <<EOF
[Unit]
Description=MeshChatX (Reticulum web UI) attached to lnsd shared instance
After=default.target

[Service]
ExecStart=%h/.venvs/meshchatx/bin/meshchatx --headless --no-https \
    --host 0.0.0.0 --port 8000 \
    --reticulum-config-dir /etc/reticulum \
    --storage-dir %h/.meshchatx
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
    systemctl --user enable --now meshchatx.service
    # So the unit survives logout/WSL restart without an interactive session.
    sudo loginctl enable-linger "$USER" || warn "   linger failed — unit starts on login only"
    echo "   http://127.0.0.1:8000 (Windows browser)"
fi

say "verify"
ss -tln 2>/dev/null | grep -E ':(4242|8000) ' || warn "expected listeners missing"
systemctl is-active --quiet lnsd.service 2>/dev/null \
    && echo "   lnsd: active" || true
echo "   next: journalctl -u lnsd -f   (watch 'Serial serial_N online')"
echo "   note: log out/in once for the new group membership to apply."
